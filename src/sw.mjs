// Service worker generators.
//
// serviceWorkerSource() → an offline-first worker for a single-page shell:
//   - install saves the page and its extras into "<prefix>-<BUILD>", and REFUSES a page that
//     is a redirect (a sign-in bounce), not same-origin "basic", not HTML, or not of this
//     worker's own BUILD (bucket uploads aren't atomic);
//   - navigations to the shell are cache-first; updates arrive as a new worker, never by
//     waiting on the network;
//   - activate deletes every other "<prefix>-*" cache (and nothing else);
//   - requests under the API prefix are left to the page (which keeps its own feed cache);
//   - the page can ask the worker its BUILD over a MessageChannel ("build").
//
// killSwitchSource() → a worker that deletes EVERY cache for the origin and unregisters
// itself. Publish it in place of sw.js to recover devices stuck on a bad worker.

// These two run inside the worker too: they are embedded with Function.prototype.toString(),
// so they must stay self-contained.
export function goodResponse(r) {
  return !!r && r.ok === true && r.type === 'basic' && !r.redirected;
}
export function isPageResponse(r) {
  return goodResponse(r) && String((r.headers && r.headers.get('content-type')) || '').includes('text/html');
}

const lit = (v) => JSON.stringify(v);
const rel = (p) => String(p).replace(/^\/+/, '');

export function serviceWorkerSource({
  build,
  cachePrefix,
  apiPrefix = '/api/',
  page = 'index.html',
  extras = [],
  timeoutMs = 3000,
}) {
  if (!build || !cachePrefix) throw new Error('serviceWorkerSource needs build and cachePrefix');
  if (!/^[A-Za-z0-9_-]+$/.test(cachePrefix)) throw new Error('cachePrefix must be [A-Za-z0-9_-]+');
  return `// Service worker, build ${build}. Generated by pwa-kit.
const BUILD = ${lit(build)};
const PREFIX = ${lit(cachePrefix + '-')};
const CACHE = PREFIX + BUILD;
const PAGE = ${lit(rel(page))};
const EXTRAS = ${lit(extras.map(rel))};
const SCOPE = new URL(self.registration.scope).pathname;
const API = SCOPE + ${lit(rel(apiPrefix))};
const TIMEOUT_MS = ${Number(timeoutMs) || 3000};

${goodResponse.toString()}
${isPageResponse.toString()}
async function ownPage(r) {
  // A real copy of THIS build's page: never a sign-in page, an error, or a half-published build.
  return isPageResponse(r) && (await r.clone().text()).includes(BUILD);
}
function timed(req, ms = TIMEOUT_MS) {
  const ac = new AbortController();
  const t = setTimeout(() => ac.abort(), ms);
  return fetch(req, { signal: ac.signal }).finally(() => clearTimeout(t));
}

async function saveShell() {
  const res = await fetch(PAGE, { cache: "no-cache", credentials: "same-origin" });
  if (!(await ownPage(res))) throw new Error("pwa-kit: refusing to install: page is missing, signed out, or from another build");
  const c = await caches.open(CACHE);
  await c.put(PAGE, res);
  await Promise.all(EXTRAS.map(async (u) => {
    try { const r = await fetch(u, { cache: "no-cache", credentials: "same-origin" }); if (goodResponse(r)) await c.put(u, r); } catch (e) { /* an icon can wait */ }
  }));
}

self.addEventListener("install", (e) => {
  e.waitUntil(saveShell().then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys()
    .then((ks) => Promise.all(ks.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("message", (e) => {
  if (e.data === "build" && e.ports && e.ports[0]) e.ports[0].postMessage(BUILD);
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith(API)) return; // live data: the page handles it
  if (req.mode === "navigate") {
    if (url.pathname !== SCOPE && url.pathname !== SCOPE + PAGE) return; // sign-in, sign-out and the rest: network
    e.respondWith(caches.open(CACHE).then(async (c) => {
      const hit = await c.match(PAGE);
      if (hit) return hit;
      const r = await fetch(req); // nothing saved yet (or storage was cleared)
      if (await ownPage(r)) await c.put(PAGE, r.clone());
      return r;
    }));
    return;
  }
  const path = url.pathname.slice(SCOPE.length);
  if (!EXTRAS.includes(path)) return;
  e.respondWith(caches.match(req, { cacheName: CACHE, ignoreSearch: true })
    .then((hit) => hit || timed(req).catch(() => Response.error())));
});
`;
}

export function killSwitchSource({ build = 'kill-switch' } = {}) {
  return `// Service worker KILL SWITCH (${build}). Generated by pwa-kit.
// Deletes every cache for this origin, then unregisters itself. Pages load from the network
// until a normal build is published again.
self.addEventListener("install", (e) => { e.waitUntil(self.skipWaiting()); });
self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.map((k) => caches.delete(k)));
    await self.registration.unregister();
  })());
});
self.addEventListener("message", (e) => {
  if (e.data === "build" && e.ports && e.ports[0]) e.ports[0].postMessage("kill-switch");
});
`;
}
